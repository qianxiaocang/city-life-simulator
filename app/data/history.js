/** Matching uses residence at the event year. A birthplace alone never creates exposure. */
export function matchesHistoryLocation(event, location) {
  const scope=event.appliesTo;
  if (!scope || !location || !scope.regions?.includes(location.region)) return false;
  if(typeof scope.urban==='boolean'&&location.urban!==scope.urban)return false;
  const hasLocations = scope.locationIds.length;
  const hasProvinces = scope.provinceIds.length;
  if (!hasLocations && !hasProvinces) return true;
  const parentCandidates = new Set([location.id, location.parentId]);
  if (location.id.startsWith('cn-') && /^cn-\d{6}$/.test(location.id)) {
    parentCandidates.add(location.id.slice(0, 7) + '00');
  }
  return !!(hasLocations && scope.locationIds.some(id => parentCandidates.has(id))
    || hasProvinces && scope.provinceIds.includes(location.province?.id));
}
export function eventsForYear(input, legacyLocation) {
  const {year, location} = typeof input === 'number' ? {year:input,location:legacyLocation} : input;
  if (!Number.isInteger(year) || year < 1950 || year > 2026) return [];
  return HISTORY_EVENTS.filter(event => event.year === year && matchesHistoryLocation(event, location));
}
/** Active effects may continue after a milestone. Log the historical text only at event.year. */
export function activeHistoryEffects(year, location) {
  return HISTORY_EVENTS.filter(event => year >= event.year && year <= event.endYear && matchesHistoryLocation(event, location));
}
/** Indices are game calibration, not an official city GDP, mortality or education series. */
export function getHistoricalEra(year, region = 'mainland') {
  const y = Math.max(1950, Math.min(2026, Math.floor(Number(year) || 2026)));
  const era = HISTORICAL_ERAS.find(item => y >= item.startYear && y <= item.endYear);
  const adjusted = {...era, year:y, requestedYear:year, region, projection:year > 2026, historical:year <= 2026, modelNote:era.modelNote};
  if (region !== 'mainland') {
    // Do not impose mainland institutional disruptions on Taiwan, Hong Kong or Macao.
    adjusted.title = {zhCN:'地区发展与生活条件（情景模型）',zhTW:'地區發展與生活條件（情景模型）',en:'Regional development and living conditions (scenario model)'};
    adjusted.sourceIds = [];
    adjusted.parameterKind = 'regional-scenario-not-regional-official-statistics';
    const early = Math.max(0, 2026-y) / 76;
    adjusted.incomeIndex = Math.max(.2, 1 - early * .72);
    adjusted.educationAccess = Math.max(.55, .96 - early * .38);
    adjusted.urbanization = region === 'taiwan' ? Math.max(.35, .8 - early*.4) : Math.max(.7,.98-early*.24);
    adjusted.healthcare = Math.max(.45,.95-early*.44);
  }
  return adjusted;
}
